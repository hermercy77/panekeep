export const MESSAGES: Record<AppLanguage, Record<MessageKey, Message>> = { "zh-CN": zhCN, en };

export function isAppLanguage(value: unknown): value is AppLanguage {
  return typeof value === "string" && APP_LANGUAGES.includes(value as AppLanguage);
}

export function translate(language: AppLanguage, key: MessageKey, variables: Variables = {}): string {
  const message = MESSAGES[language][key];
  return typeof message === "function" ? message(variables) : message;
}
